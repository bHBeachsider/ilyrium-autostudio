#!/usr/bin/env python3
r"""build_queue.py - the missing-asset queue, as a table rather than a hope (Phase 3, task 19; proposal s10).

Rows come from three places and are merged by (kind, noun):
  1. resolve_scene.py build requests    - what the next sequence names and the catalog cannot supply
  2. the provenance ledger              - assets whose keys were re-generated most often (an asset the generator keeps
                                          getting wrong is an asset that wants a hero-grade build)
  3. FINDINGS.md incident ids           - a finding that names an asset raises it (passed in as --findings, optional)
Score = scenes_needing * 3 + regenerations * 1 + findings * 2; ties by first scene. Output: build_queue.json and a
markdown table for the human. This is the self-expanding loop's to-do list; nothing here builds anything.

usage: build_queue.py [--requests agent/resolved/*_build_requests.json ...] [--findings FINDINGS.md] [--out DIR]
"""
import argparse
import collections
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
sys.path.insert(0, os.path.dirname(PKG))


def regenerations():
    """asset -> number of ledger rows (keyframes + edits) whose shot's set is that asset; a crude demand signal."""
    try:
        from backlot.provenance import ledger
    except Exception:
        return {}
    counts = collections.Counter()
    shot_set = {"SH003": "RallyStage", "SH006": "RallyStage", "SH007": "RallyStage", "SH009": "RallyStage",
                "SH010": "RallyStage", "SH012": "Banner", "SH002": "Square", "PLATE": "Square"}
    for r in ledger.rows():
        if r.get("kind") in ("keyframe", "edit") and r.get("shot") in shot_set:
            counts[shot_set[r["shot"]]] += 1
    return counts


def findings_mentions(path):
    if not path or not os.path.exists(path):
        return collections.Counter()
    text = open(path, encoding="utf-8", errors="ignore").read().lower()
    c = collections.Counter()
    for word, asset in (("stage", "RallyStage"), ("dais", "RallyStage"), ("banner", "Banner"), ("post", "RallyStage"),
                        ("chair", "RallyStage"), ("pumpkin", "harvest dressing"), ("hay", "harvest dressing"),
                        ("workm", "Mannequins"), ("office", "PengoldOffice")):
        c[asset] += len(re.findall(r"nh-usa-\d+[^\n]*" + word, text))
    return c


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--requests", nargs="*", default=glob.glob(os.path.join(PKG, "agent", "resolved", "*_build_requests.json")))
    ap.add_argument("--findings"); ap.add_argument("--out", default=os.path.join(PKG, "agent"))
    a = ap.parse_args()
    reqs = []
    for f in a.requests:
        reqs += json.load(open(f))
    regen = regenerations(); found = findings_mentions(a.findings)
    rows = {}
    for r in reqs:
        k = (r["kind"], (r.get("noun") or "").strip().lower()[:60])
        row = rows.setdefault(k, dict(kind=r["kind"], noun=r.get("noun"), asset=r.get("asset"), scenes=[], reasons=set()))
        row["scenes"].append(r.get("scene")); row["reasons"].add(r.get("reason"))
    # assets the ledger says were regenerated a lot become HERO-grade requests even with no scene asking
    for asset, n in regen.items():
        if n >= 10:
            k = ("hero_grade", asset.lower())
            rows.setdefault(k, dict(kind="hero_grade", noun="hero-grade %s" % asset, asset=asset, scenes=[], reasons=set()))
            rows[k]["reasons"].add("%d generations recorded against this asset in the ledger" % n)
    out = []
    for (kind, _), row in rows.items():
        asset = row.get("asset") or ""
        score = 3 * len(set(s for s in row["scenes"] if s is not None)) + regen.get(asset, 0) + 2 * found.get(asset, 0)
        out.append(dict(kind=kind, noun=row["noun"], asset=row["asset"] or None, scenes=sorted(set(s for s in row["scenes"] if s is not None)),
                        regenerations=regen.get(asset, 0), findings=found.get(asset, 0), score=score, reasons=sorted(row["reasons"])))
    out.sort(key=lambda r: (-r["score"], r["scenes"][0] if r["scenes"] else 999))
    os.makedirs(a.out, exist_ok=True)
    json.dump(out, open(os.path.join(a.out, "build_queue.json"), "w"), indent=1)
    md = ["# Build queue (generated by backlot/agent/build_queue.py)", "",
          "| # | kind | what | asset | scenes | regen | findings | score | why |", "|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(out, 1):
        md.append("| %d | %s | %s | %s | %s | %d | %d | %d | %s |" % (i, r["kind"], (r["noun"] or "")[:60], r["asset"] or "—",
                  ",".join(map(str, r["scenes"])) or "—", r["regenerations"], r["findings"], r["score"], "; ".join(r["reasons"])[:120]))
    open(os.path.join(a.out, "BUILD_QUEUE.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
