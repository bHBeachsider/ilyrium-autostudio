"""
build_anchor_manifest - assemble the Stage-3 hero-anchor render manifest.

Reads each principal's LOCKED VISUAL DESCRIPTOR out of the character bible, merges it
with the project style kernel (look, register, casting canon, negatives, engine tails)
and emits ANCHOR_MANIFEST.json: one fully-assembled prompt per character per angle,
ready for either render path.

    python build_anchor_manifest.py                 # write ANCHOR_MANIFEST.json
    python build_anchor_manifest.py --print summer  # eyeball one character's prompts

Stage 3 is the input to everything at Gate 2 - anchors gate the LoRAs, the LoRAs gate
the keyframes, the keyframes gate every shot. This script exists so that step is one
command and not an afternoon of copy-paste.

LEGAL: every prompt specifies age, origin, build, wardrobe and affect only. Never a
likeness to a real person. The release gate checks this; so does the kernel's legal_rule.

Pure stdlib. No network, no spend. It writes a manifest; it does not render.
"""

import argparse
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.abspath(os.path.join(HERE, "..", ".."))
BIBLE = os.path.join(PROJECT, "01_development", "bible", "characters")
KERNEL = os.path.join(PROJECT, "style_kernel.json")
OUT = os.path.join(HERE, "anchors", "ANCHOR_MANIFEST.json")

# Principals first - these four gate Gate 2. Philip and Bildersatz are portrait-only
# (Philip is offstage; Bildersatz exists solely as the single authorized 1996 portrait).
PRINCIPALS = ["summer", "pengold", "dick", "valencia"]
SECONDARY = ["philip", "bildersatz"]

# 3 angles x 2 aspects. 21:9 feeds shot keyframes; 3:2 feeds LoRA training and print.
ANGLES = {
    "front": "straight-on frontal portrait, eyes to lens but not performing, neutral sincere expression",
    "three_quarter": "three-quarter turn, gaze slightly off-lens, weight settled, unposed",
    "close": "tight close-up from the collarbone, shallow depth of field, the face doing nothing dramatic",
}
ASPECTS = {"21:9": "cinematic ultrawide framing", "3:2": "standard portrait framing"}

# The descriptor's backtick block sits on the next line for most characters and on the
# same line for bildersatz - match either.
DESCRIPTOR_RE = re.compile(
    r"LOCKED VISUAL DESCRIPTOR.*?`([^`]+)`", re.DOTALL)


def locked_descriptor(key):
    path = os.path.join(BIBLE, key, "bible.md")
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    m = DESCRIPTOR_RE.search(text)
    if not m:
        raise SystemExit(
            "no LOCKED VISUAL DESCRIPTOR found in %s - lock it in the bible first" % path)
    return " ".join(m.group(1).split())


def build(kernel):
    look = kernel["look"]
    register = kernel["register"]
    negatives = kernel["negatives"]
    casting = kernel.get("casting_canon", {})

    entries = []
    for key in PRINCIPALS + SECONDARY:
        descriptor = locked_descriptor(key)
        tier = "principal" if key in PRINCIPALS else "secondary"
        angles = ANGLES if tier == "principal" else {"front": ANGLES["front"]}
        for angle, angle_text in angles.items():
            for aspect, aspect_text in ASPECTS.items():
                entries.append({
                    "character": key,
                    "tier": tier,
                    "angle": angle,
                    "aspect_ratio": aspect,
                    "output": "anchors/%s_%s_%s.png" % (
                        key, angle, aspect.replace(":", "x")),
                    "prompt": ", ".join([
                        descriptor, angle_text, aspect_text, look, register,
                    ]),
                    "negative_prompt": negatives,
                    "casting_canon": casting.get(key, ""),
                    "purpose": ("LoRA training set + keyframe reference"
                                if aspect == "3:2" else "shot keyframe reference"),
                })

    return {
        "$comment": (
            "Stage-3 hero anchors for NEW HARNOMY, U.S.A. Generated by "
            "build_anchor_manifest.py from the bible's LOCKED VISUAL DESCRIPTORs and "
            "style_kernel.json. Regenerate after any descriptor or kernel change."),
        "project": "new_harnomy_usa",
        "stage": "03_design/characters",
        "kernel_look": look,
        "kernel_register": register,
        "legal_rule": kernel.get("legal_rule", ""),
        "engine_hints": {
            "on_box": ("comfyui FLUX.2 Klein via ilyrium-shots/keyframe_to_comfy.py; "
                       "cheapest path, needs the g6 box running"),
            "cloud": ("higgsfield:soul_cinematic at 0.12 cr/still, 21:9 2k per "
                      "style_kernel.engine_tails.higgsfield"),
        },
        "acceptance": [
            "No likeness to any real public figure (release-gate check A4).",
            "Same face across all angles for one character before any LoRA training.",
            "Register held: no smile at camera, no eyebrow lift, no dramatic gesture.",
            "Mauve, where it appears, reads brownish and dusty - never lavender.",
        ],
        "next_steps": [
            "1. Render this manifest; Brad approves one anchor set per principal.",
            "2. Train one LoRA per principal on the box (ilyrium-shots/train_lora.py); "
            "register in loras/lora_library.json.",
            "3. Verification stills must match the approved anchor before Gate 2 keyframes.",
        ],
        "counts": {
            "principals": len(PRINCIPALS),
            "secondary": len(SECONDARY),
            "renders": len(entries),
        },
        "entries": entries,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", dest="who", default=None,
                    help="print one character's prompts instead of writing the manifest")
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args()

    with open(KERNEL, encoding="utf-8") as fh:
        kernel = json.load(fh)
    manifest = build(kernel)

    if args.who:
        for e in manifest["entries"]:
            if e["character"] == args.who:
                print("\n[%s %s]\n%s" % (e["angle"], e["aspect_ratio"], e["prompt"]))
        return

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
        fh.write("\n")
    print("[OK] %s" % args.out)
    print("     %d renders: %d principals x 3 angles x 2 aspects + %d secondary x 2"
          % (manifest["counts"]["renders"], manifest["counts"]["principals"],
             manifest["counts"]["secondary"]))


if __name__ == "__main__":
    main()
